/**
 * Per TRD-02 v0.2 §4.4.
 *
 * Bidirectional drift-aware sync mapping for a single Orbital aggregate to
 * Monday.com. last_seen_item_ids is added in this phase to track items the
 * reconciliation pull last observed (TRD-02 §13.3).
 */
export const mondaySyncState = pgTable(
  'monday_sync_state',
  {
    syncStateId: uuid('sync_state_id').primaryKey(),
    aggregateType: text('aggregate_type', { enum: MONDAY_AGGREGATE_TYPE }).notNull(),
    aggregateId: uuid('aggregate_id').notNull(),
    mondayId: text('monday_id').notNull(),
    lastPushAt: timestamp('last_push_at', { withTimezone: true, mode: 'date' }),
    lastPullAt: timestamp('last_pull_at', { withTimezone: true, mode: 'date' }),
    lastPushHash: text('last_push_hash'),
    lastPullHash: text('last_pull_hash'),
    lastSeenItemIds: jsonb('last_seen_item_ids').$type<string[]>().notNull().default([]),
    driftDetectedAt: timestamp('drift_detected_at', { withTimezone: true, mode: 'date' }),
    syncErrorCount: integer('sync_error_count').notNull().default(0),
    lastError: text('last_error'),
    schemaVersion: integer('schema_version').notNull().default(1),
  },
  (t) => ({
    byAggregate: uniqueIndex('monday_sync_aggregate_uq').on(t.aggregateType, t.aggregateId),
    byMondayId: index('monday_sync_monday_idx').on(t.mondayId),
  }),
)

export type MondaySyncStateRow = typeof mondaySyncState.$inferSelect
export type MondaySyncStateInsert = typeof mondaySyncState.$inferInsert
