/**
 * Per TRD-02 v0.2 §4.1.
 *
 * One epic groups N stories. Linked to a vision version. Priority is dense.
 */
export const epics = pgTable(
  'epics',
  {
    epicId: uuid('epic_id').primaryKey(),
    /**
     * Round 7-01 — Multi-tenant scoping.
     * Sentinel '00000000-0000-0000-0000-000000000000' = local-install default.
     * [Engineer-Sr · Sonnet · run-round7-01-extract-hub]
     */
    tenantId: uuid('tenant_id').notNull().default('00000000-0000-0000-0000-000000000000'),
    /**
     * fix/multi-project-isolation — multi-project scoping.
     * Mirrors migration 0015. Nullable until backfill (0045) + NOT NULL (0046).
     * [Engineer-Principal · Opus · run-multi-project-isolation]
     */
    projectId: uuid('project_id'),
    visionVersionId: uuid('vision_version_id').notNull(),
    title: text('title').notNull(),
    rationale: text('rationale').notNull(),
    priority: integer('priority').notNull(),
    mondayGroupId: text('monday_group_id'),
    status: text('status', { enum: EPIC_STATUS }).notNull().default('draft'),
    /**
     * Migration 0018: set by VisionAutoDecomposeSubscriber when auto-generating
     * starter epics from a locked vision. NULL for manually-created epics.
     * Shape: { source: 'vision_lock', vision_document_id: string, version: number }
     */
    autoGeneratedMetadata: jsonb('auto_generated_metadata')
      .$type<{
        source: 'vision_lock'
        vision_document_id: string
        version: number
      } | null>()
      .default(null),
    createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' })
      .notNull()
      .defaultNow(),
    schemaVersion: integer('schema_version').notNull().default(1),
  },
  (t) => ({
    byVision: index('epics_vision_idx').on(t.visionVersionId),
    byPriority: index('epics_priority_idx').on(t.priority),
    byProject: index('epics_project_idx').on(t.projectId),
  }),
)

export type EpicRow = typeof epics.$inferSelect
export type EpicInsert = typeof epics.$inferInsert

