/**
 * sprint-tick-worker.test.ts
 *
 * [Engineer-Sr · Sonnet · run-sprint-loop]
 *
 * Unit tests for SprintTickWorker. Uses an in-memory stub DB to verify:
 *   - Idempotency: concurrent ticks for the same tenant skip via SKIP LOCKED simulation
 *   - Capacity: never spawns more runs than max_concurrent_runs
 *   - Tenant isolation: tick only touches stories in the correct tenant
 *   - Workflow transitions: Ready→InProgress, InProgress→Review, Review→Done
 *   - Sprint auto-complete: fires when all stories reach Done
 *   - story-pr-pipeline stub: logs clear error, does not fake success
 */

