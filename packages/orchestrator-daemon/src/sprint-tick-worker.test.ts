// ---------------------------------------------------------------------------
// Stub SprintTickWorkerDeps
// ---------------------------------------------------------------------------

function makeDeps(overrides: Partial<SprintTickWorkerDeps> = {}): SprintTickWorkerDeps {
  const sprints = [makeStubSprint()]
  const stories = [makeStubStory()]
  const tickLogs: unknown[] = []
  const storyPrRuns: unknown[] = []
  const storyUpdates: Array<{ storyId: string; status: string }> = []
  const sprintUpdates: Array<{ sprintId: string; status: string }> = []

  return {
    instanceId: 'daemon-test-1',
    tenantId: 'tenant-a',

    acquireLease: vi.fn().mockResolvedValue(true),
    releaseLease: vi.fn().mockResolvedValue(undefined),

    listActiveSprintsForTenant: vi.fn().mockResolvedValue(sprints),

    listStoriesForSprint: vi.fn().mockResolvedValue(stories),

    countInProgressStoriesForSprint: vi.fn().mockResolvedValue(0),

    getPolicy: vi.fn().mockResolvedValue({
      maxConcurrentRuns: 3,
      capacityOverride: 0,
    }),

    updateStoryStatus: vi.fn().mockImplementation(async (storyId: string, status: string) => {
      storyUpdates.push({ storyId, status })
      const s = stories.find((x) => x.storyId === storyId)
      if (s) s.status = status
    }),

    writeTickLog: vi.fn().mockResolvedValue(undefined),

    spawnStoryPrRun: vi.fn().mockResolvedValue({ runId: 'run-1', status: 'spawning' as const }),

    insertStoryPrRun: vi.fn().mockResolvedValue(undefined),

    updateStoryPrRun: vi.fn().mockResolvedValue(undefined),

    autoCompleteSprint: vi.fn().mockResolvedValue(undefined),

    checkStoryPrRunPipeline: vi.fn().mockResolvedValue({ available: true }),

    ...overrides,

    // expose for assertions
    _storyUpdates: storyUpdates,
    _sprintUpdates: sprintUpdates,
    _tickLogs: tickLogs,
    _storyPrRuns: storyPrRuns,
  } as SprintTickWorkerDeps & {
    _storyUpdates: typeof storyUpdates
    _sprintUpdates: typeof sprintUpdates
    _tickLogs: typeof tickLogs
    _storyPrRuns: typeof storyPrRuns
  }
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

describe('SprintTickWorker', () => {
  let worker: SprintTickWorker
  let deps: ReturnType<typeof makeDeps>

  beforeEach(() => {
    deps = makeDeps()
    worker = new SprintTickWorker(deps)
  })

  describe('lease / idempotency', () => {
    it('skips the tick entirely when the lease cannot be acquired', async () => {
      deps.acquireLease = vi.fn().mockResolvedValue(false)
      const result = await worker.runTick()
      expect(result.skipped).toBe(true)
      expect(deps.listActiveSprintsForTenant).not.toHaveBeenCalled()
    })

    it('runs the tick when the lease is acquired', async () => {
      const result = await worker.runTick()
      expect(result.skipped).toBe(false)
    })

    it('releases the lease after a successful tick', async () => {
      await worker.runTick()
      expect(deps.releaseLease).toHaveBeenCalledOnce()
    })

    it('releases the lease even when the tick throws', async () => {
      deps.listActiveSprintsForTenant = vi.fn().mockRejectedValue(new Error('db error'))
      await expect(worker.runTick()).rejects.toThrow('db error')
      expect(deps.releaseLease).toHaveBeenCalledOnce()
    })
  })

  describe('capacity enforcement', () => {
    it('does not spawn when in_progress count equals max_concurrent_runs', async () => {
      deps.countInProgressStoriesForSprint = vi.fn().mockResolvedValue(3)
      deps.getPolicy = vi.fn().mockResolvedValue({ maxConcurrentRuns: 3, capacityOverride: 0 })
      await worker.runTick()
      expect(deps.spawnStoryPrRun).not.toHaveBeenCalled()
    })

    it('spawns when in_progress count is below max_concurrent_runs', async () => {
      deps.countInProgressStoriesForSprint = vi.fn().mockResolvedValue(1)
      deps.getPolicy = vi.fn().mockResolvedValue({ maxConcurrentRuns: 3, capacityOverride: 0 })
      await worker.runTick()
      expect(deps.spawnStoryPrRun).toHaveBeenCalledOnce()
    })
  })

  describe('tenant isolation', () => {
    it('only processes sprints for the configured tenant', async () => {
      // Sprint with different tenant is NOT returned by listActiveSprintsForTenant
      // which already filters by tenantId — so we verify that the correct
      // tenantId was passed to listActiveSprintsForTenant.
      await worker.runTick()
      expect(deps.listActiveSprintsForTenant).toHaveBeenCalledWith('tenant-a')
    })
  })

  describe('workflow transitions', () => {
    it('transitions a ready story to in_progress and writes tick log', async () => {
      await worker.runTick()
      expect(deps.updateStoryStatus).toHaveBeenCalledWith('story-1', 'in_progress', expect.any(String))
      expect(deps.writeTickLog).toHaveBeenCalledWith(
        expect.objectContaining({
          storyId: 'story-1',
          fromStatus: 'ready',
          toStatus: 'in_progress',
          tenantId: 'tenant-a',
          sprintId: 'sprint-1',
        }),
      )
    })

    it('spawns a story_pr_run for the picked story', async () => {
      await worker.runTick()
      expect(deps.spawnStoryPrRun).toHaveBeenCalledWith(
        expect.objectContaining({ storyId: 'story-1', sprintId: 'sprint-1', tenantId: 'tenant-a' }),
      )
    })
  })

  describe('sprint auto-complete', () => {
    it('calls autoCompleteSprint when all stories are done', async () => {
      deps.listStoriesForSprint = vi.fn().mockResolvedValue([
        makeStubStory({ status: 'done' }),
        makeStubStory({ storyId: 'story-2', status: 'done' }),
      ])
      await worker.runTick()
      expect(deps.autoCompleteSprint).toHaveBeenCalledWith('sprint-1', 'tenant-a')
    })

    it('does not call autoCompleteSprint when some stories remain', async () => {
      // Default: one story with status 'ready'
      await worker.runTick()
      // After the tick, story moves to in_progress — not done — so no auto-complete
      expect(deps.autoCompleteSprint).not.toHaveBeenCalled()
    })
  })

  describe('story-pr-pipeline stub', () => {
    it('surfaces a clear error when pipeline is unavailable, not a fake success', async () => {
      deps.checkStoryPrRunPipeline = vi.fn().mockResolvedValue({ available: false, reason: 'NOT_MERGED: story-pr-pipeline Lambda not registered' })
      deps.spawnStoryPrRun = vi.fn().mockRejectedValue(
        new Error('story-pr-pipeline not available: NOT_MERGED: story-pr-pipeline Lambda not registered'),
      )

      // The tick should still complete; the story gets reverted to 'ready'
      const result = await worker.runTick()
      expect(result.errors).toHaveLength(1)
      expect(result.errors[0]).toMatch(/story-pr-pipeline not available/)
    })
  })
})

